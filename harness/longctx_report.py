"""Builds results/longctx_report.md from results/longctx_*.jsonl (MEASURED step costs) + approx-sweep acceptance (INFERRED projections).
Round model (same as H5, which matched measured wall within ~3%): round = gamma * T_draft + T_verify(K=gamma+1); committed = a + 1.
Acceptance: iid per-position accept prob p fitted so that sum_{k<=4} p^k = a4 (a4 = committed-1 at gamma=4 from approx_sweep_quick1 / H5);
a(gamma)=sum_{k<=gamma} p^k; lock-step batch commits E[min_b a_b]+1 with E[min over B] = sum_k p^(kB)  (INFERRED; eager A100 run2 measured
a_min 1.69 (B=2) / 1.27 (B=4) vs model below); 'ragged' = each sequence commits its own a+1 (needs per-sequence positions; same kernel cost, upper bound)."""
import glob, json, sys, collections

ACC = {  # committed per verify block at gamma=4, results/approx_sweep_quick1.json (A100, ctx<=8K, 2 prompts, n=4) ; fixed256 assumed = oracle256
    "top4": 3.7578, "attn256": 4.7005, "attn256+top4": 3.9297}


def p_of(committed4):
    a, lo, hi = committed4 - 1, 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if sum(mid ** k for k in range(1, 5)) < a: lo = mid
        else: hi = mid
    return lo


def acc(p, gamma, B=1, lock=True):
    q = p ** B if lock else p
    return sum(q ** k for k in range(1, gamma + 1))


def load(pattern):
    rows = []
    for f in sorted(glob.glob(pattern)):
        rows += [json.loads(l) for l in open(f) if l.strip()]
    return rows


def main(out="results/longctx_report.md"):
    L = []
    P = L.append
    A = {}
    for r in load("results/longctx_lcA*.jsonl"):
        if r.get("kind") == "cell" and "ms" in r:
            A[(r["ctx"], r["cell"])] = r["ms"]
    ctxs = sorted({c for c, _ in A})
    P("# longctx-batch report (generated by harness/longctx_report.py)\n")
    P("## A. Long context, batch 1, H100, CUDA-graph replay ms/step (MEASURED, lcA*)\n")
    keys = ["T1_rNone_pad", "T1_rNone_win", "T1_rNone_tri", "T1_r4_pad", "T1_r4_win", "T1_r4_tri", "T1_rNone_gather_fixed256", "T1_rNone_triidx_fixed256",
            "T1_rNone_gather_oracle256", "T1_rNone_triidx_oracle256", "T1_r4_gather_fixed256", "T1_r4_triidx_fixed256", "T1_r4_gather_oracle256",
            "T1_r4_triidx_oracle256", "T1_rNone_noattn", "T1_r4_noattn", "verify_K3_win", "verify_K5_win", "verify_K5_tri", "verify_K9_win", "verify_K5_noattn"]
    P("| cell | " + " | ".join(str(c) for c in ctxs) + " |\n|---|" + "---|" * len(ctxs))
    for k in keys:
        P(f"| {k} | " + " | ".join(f"{A[(c, k)]:.2f}" if (c, k) in A else "-" for c in ctxs) + " |")
    P("\n## A2. Projected self-spec speedup vs plain dense decode at the same ctx, gamma in 2/4 (INFERRED; step costs MEASURED, acceptance from approx_sweep)\n")
    P("plain = T1_rNone_win (window-aware dense). verify = verify_K{gamma+1}_win. Draft variants: dense top-4 | sparse256 fixed index + top-4 | sparse256 oracle index (selector scan) + top-4 | attn-only sparse (all experts).\n")
    P("| ctx | gamma | draft | T_draft | round ms | committed | tok/s speedup |\n|---|---|---|---|---|---|---|")
    drafts = [("dense+top4", "T1_r4_win", "top4"), ("fixed256+top4 (cached index)", "T1_r4_triidx_fixed256", "attn256+top4"),
              ("oracle256+top4", "T1_r4_triidx_oracle256", "attn256+top4"), ("fixed256 attn-only (cached index)", "T1_rNone_triidx_fixed256", "attn256"),
              ("oracle256 attn-only", "T1_rNone_triidx_oracle256", "attn256")]
    for c in ctxs:
        plain = A.get((c, "T1_rNone_win"))
        for g in (2, 4):
            vk = A.get((c, f"verify_K{g + 1}_win"))
            if plain is None or vk is None: continue
            for nm, key, an in drafts:
                td = A.get((c, key))
                if td is None: continue
                p = p_of(ACC[an]); com = acc(p, g) + 1
                rnd = g * td + vk
                P(f"| {c} | {g} | {nm} | {td:.2f} | {rnd:.1f} | {com:.2f} | {plain * com / rnd:.2f}x |")
    # B
    Bm = {}
    for r in load("results/longctx_lcB*.jsonl"):
        if r.get("kind") == "cell" and "ms" in r:
            Bm[(r["ctx"], r["B"], r["cell"])] = r["ms"]
    P("\n## B. Batched lock-step step cost, H100 graphed (MEASURED, lcB*; window-slice bmm attention 'win', Triton 'tri')\n")
    bc = sorted({(c, b) for c, b, _ in Bm})
    P("| ctx | B | plain step | draft r4 | verify K3 | verify K5 | verify K9 | plain/seq | noattn T1 | noattn K5 |\n|---|---|---|---|---|---|---|---|---|---|")
    g = lambda c, b, k: Bm.get((c, b, k))
    for c, b in bc:
        f = lambda v: f"{v:.2f}" if v is not None else "-"
        P(f"| {c} | {b} | {f(g(c, b, 'T1_full_win'))} | {f(g(c, b, 'T1_draft_r4_win'))} | {f(g(c, b, 'verify_K3_win'))} | {f(g(c, b, 'verify_K5_win'))} | "
          f"{f(g(c, b, 'verify_K9_win'))} | {f(g(c, b, 'T1_full_win') / b if g(c, b, 'T1_full_win') else None)} | {f(g(c, b, 'T1_noattn'))} | {f(g(c, b, 'verify_K5_noattn'))} |")
    P("\n## B2. Projected self-spec (top-4 expert draft) vs plain batched decode (INFERRED). gamma=4 unless noted; speedup = plain_step*(a+1) / round\n")
    p = p_of(ACC["top4"])
    P(f"fitted p={p:.3f}; lock-step a_min: " + ", ".join(f"B={b}: {acc(p, 4, b):.2f}" for b in (1, 2, 4, 8)) + " (eager A100 measured 2.40@B1, 1.69@B2, 1.27@B4)\n")
    P("| ctx | B | gamma | round ms | lock-step speedup | ragged (per-seq commit) speedup |\n|---|---|---|---|---|---|")
    for c, b in bc:
        for gm in (2, 4):
            pl, td, vk = g(c, b, "T1_full_win"), g(c, b, "T1_draft_r4_win"), g(c, b, f"verify_K{gm + 1}_win")
            if None in (pl, td, vk): continue
            rnd = gm * td + vk
            P(f"| {c} | {b} | {gm} | {rnd:.1f} | {pl * (acc(p, gm, b) + 1) / rnd:.2f}x | {pl * (acc(p, gm, 1, False) + 1) / rnd:.2f}x |")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(*sys.argv[1:])
